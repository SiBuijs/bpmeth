class WigglerSegment:
    def __init__(self, a_list, b_list, bs, s0=0, length=0, x0=0, y0=0, curv=0):
        self.s0 = s0
        self.length = length
        self.x0 = x0
        self.y0 = y0
        self.scale = 1.0

        # TODO: These tuples might not be needed here.
        # TODO: Will look into where they can be put instead.
        self.bs = bs
        self.a = tuple(a_list)
        self.b = tuple(b_list)
        self.curv = curv

        # bpmeth objects / expressions / callables (constructed lazily)
        self.wiggler_map = None

        self.Bxexpr = None
        self.Byexpr = None
        self.Bsexpr = None
        self.Bxfun = None
        self.Byfun = None
        self.Bsfun = None

        self.Axexpr = None
        self.Ayexpr = None
        self.Asexpr = None
        self.Axfun = None
        self.Ayfun = None
        self.Asfun = None

    def get_field(self, x, y, s):
        return (self.scale * self.Bxfun(x - self.x0, y - self.y0, s),
                self.scale * self.Byfun(x - self.x0, y - self.y0, s),
                self.scale * self.Bsfun(x - self.x0, y - self.y0, s))

    # Order of arguments: (x, y, s). Vectorized.
    def get_vector_potential(self, x, y, s):
        Ax = self.scale * self.Axfun(x - self.x0, y - self.y0, s)
        Ay = self.scale * self.Ayfun(x - self.x0, y - self.y0, s)
        As = self.scale * self.Asfun(x - self.x0, y - self.y0, s)
        return Ax, Ay, As


