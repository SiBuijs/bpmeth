    def set_segments(self):
        N = self.field_fitter.deg + 1  # number of derivatives per field

        # --- Export all derivative data ---
        segs_Bx = [self.field_fitter._export_piecewise_segments("Bx", der=n) for n in range(N)]
        segs_By = [self.field_fitter._export_piecewise_segments("By", der=n) for n in range(N)]
        segs_Bs = self.field_fitter._export_piecewise_segments("Bs", der=0)


        # --- Build unified segmentation grid from all fields ---
        boundaries = set()
        for seg_list in segs_Bx + segs_By + [segs_Bs]:
            for s0, s1, _ in seg_list:
                boundaries.add(s0)
                boundaries.add(s1)
        s_grid = sorted(boundaries)

        # --- Create WigglerSegments based on unified grid ---
        self.segments = []
        for i in range(len(s_grid) - 1):
            s_start = s_grid[i]
            s_end = s_grid[i + 1]
            ell_j = s_end - s_start
            s_mid = 0.5 * (s_start + s_end)

            # Helper to get the segment value that covers s_mid
            def find_value(segments):
                for s0, s1, val in segments:
                    if s0 <= s_mid <= s1:
                        return val
                # fallback: last valid
                return segments[-1][2]

            # Collect all derivatives for Bx, By
            A_j = [find_value(segs_Bx[n]) for n in range(N)]
            B_j = [find_value(segs_By[n]) for n in range(N)]
            b_sj = find_value(segs_Bs)

            seg = WigglerSegment(
                a_list=A_j,
                b_list=B_j,
                bs=b_sj,
                s0=s_start,
                length=ell_j,
                x0=0.0,
                y0=0.0,
                curv=0.0,
            )
            self.segments.append(seg)
            self._lambdify_segment_from_generic(seg, deg_poly=4, n_modes=self.field_fitter.n_modes)

    def set_integrator(self, n_slices=1000, n_steps = 1000):
        if self.segments == []:
            self.set_segments()

        self.n_slices = n_slices
        l_wig = self.field_fitter.length
        s_start = self.field_fitter.s_full[0]
        s_end   = self.field_fitter.s_full[-1]

        s_cuts = np.linspace(s_start, s_end, n_slices + 1)
        #s_mid = 0.5 * (s_cuts[:-1] + s_cuts[1:])
        for ii in range(n_slices):
            wig = xt.BorisSpatialIntegrator(fieldmap_callable=self.get_field, s_start=s_cuts[ii], s_end=s_cuts[ii + 1],
                                            n_steps=np.round(n_steps / n_slices).astype(int),
                                            verbose=True)
            self.integrator.append(wig)

    def get_line(self):
        if self.integrator == []:
            self.set_integrator()

        self.env = xt.Environment()

        for ii in range(self.n_slices):
            self.env.elements[f'wigslice_{ii}'] = self.integrator[ii]
        self.wiggler_line = self.env.new_line(components=['wigslice_' + str(ii) for ii in range(self.n_slices)])
        return self.wiggler_line

